"""Generate the public API reference from ``market_sim.__all__``."""

from __future__ import annotations

import inspect
from pathlib import Path
from typing import Any, cast


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _summary(obj: Any) -> str:
    doc = inspect.getdoc(obj)
    if not doc:
        return ""
    return doc.splitlines()[0].strip()


def build_api_markdown(package: Any | None = None) -> str:
    """Build the Markdown API reference for the package."""
    if package is None:
        import market_sim as package
    module = cast(Any, package)
    lines = [
        "# API reference",
        "",
        "Generated by `python scripts/build_api_docs.py`.  Do not edit by hand.",
        "",
        "| Name | Kind | Module | Signature | Summary |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in sorted(module.__all__):
        obj = getattr(module, name)
        if inspect.isfunction(obj):
            kind = "function"
        elif inspect.isclass(obj):
            kind = "class"
        else:
            kind = "constant"
        try:
            if kind == "constant":
                simple = isinstance(obj, (int, float, str, bool))
                signature = repr(obj) if simple else type(obj).__name__
            else:
                signature = str(inspect.signature(obj))
        except (TypeError, ValueError):
            signature = ""
        module_name = getattr(obj, "__module__", "market_sim")
        summary = _escape(_summary(obj)) if kind != "constant" else ""
        lines.append(
            f"| `{name}` | {kind} | `{module_name}` | `{_escape(signature)}` | {summary} |"
        )
    return "\n".join(lines) + "\n"


def check_api_docs(root: Path) -> list[str]:
    """Return an error when ``docs/api.md`` is missing or stale."""
    path = root / "docs" / "api.md"
    expected = build_api_markdown()
    if not path.exists():
        return ["docs/api.md is missing. Run python scripts/build_api_docs.py"]
    if path.read_text(encoding="utf-8") != expected:
        return ["docs/api.md is stale. Run python scripts/build_api_docs.py"]
    return []
